/* The framebuffer is stored column by column: pixel (x, y) is at
 * px[x * GFX_H_PX + y].  That is the native layout of the CX II panel (so
 * presenting a frame is a plain copy), and it makes the things drawn most
 * often here - the activity map, filled panels and text, whose glyphs are
 * column data too - run through memory in order, which matters a great deal
 * on a CPU whose random memory accesses cost about a microsecond. */
#define AT(x, y) ((x) * GFX_H_PX + (y))

void gfx_clear(gfx_t *g, uint16_t c) {
    for (int i = 0; i < GFX_W * GFX_H_PX; i++) g->px[i] = c;
}

void gfx_pixel(gfx_t *g, int x, int y, uint16_t c) {
    if ((unsigned)x < GFX_W && (unsigned)y < GFX_H_PX) g->px[AT(x, y)] = c;
}

void gfx_vline(gfx_t *g, int x, int y0, int y1, uint16_t c) {
    if ((unsigned)x >= GFX_W) return;
    if (y0 > y1) { int t = y0; y0 = y1; y1 = t; }
    if (y0 < 0) y0 = 0;
    if (y1 >= GFX_H_PX) y1 = GFX_H_PX - 1;
    uint16_t *p = g->px + AT(x, 0);
    for (int y = y0; y <= y1; y++) p[y] = c;
}

void gfx_hline(gfx_t *g, int x0, int x1, int y, uint16_t c) {
    if ((unsigned)y >= GFX_H_PX) return;
    if (x0 > x1) { int t = x0; x0 = x1; x1 = t; }
    if (x0 < 0) x0 = 0;
    if (x1 >= GFX_W) x1 = GFX_W - 1;
    for (int x = x0; x <= x1; x++) g->px[AT(x, y)] = c;
}

void gfx_rect(gfx_t *g, int x, int y, int w, int h, uint16_t c) {
    for (int i = 0; i < w; i++) gfx_vline(g, x + i, y, y + h - 1, c);
}

void gfx_frame(gfx_t *g, int x, int y, int w, int h, uint16_t c) {
    gfx_hline(g, x, x + w - 1, y, c);
    gfx_hline(g, x, x + w - 1, y + h - 1, c);
    gfx_vline(g, x, y, y + h - 1, c);
    gfx_vline(g, x + w - 1, y, y + h - 1, c);
}

void gfx_line(gfx_t *g, int x0, int y0, int x1, int y1, uint16_t c) {
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (int guard = 0; guard < 1024; guard++) {
        gfx_pixel(g, x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void gfx_ellipse(gfx_t *g, int cx, int cy, int rx, int ry, uint16_t c) {
    if (rx <= 0 || ry <= 0) {
        gfx_pixel(g, cx, cy, c);
        return;
    }
    long rx2 = (long)rx * rx, ry2 = (long)ry * ry;
    for (int x = -rx; x <= rx; x++) {
        /* tallest y with x^2 * ry^2 + y^2 * rx^2 <= rx^2 * ry^2 */
        long rhs = rx2 * ry2 - (long)x * x * ry2;
        int y = ry;
        while (y > 0 && (long)y * y * rx2 > rhs) y--;
        gfx_vline(g, cx + x, cy - y, cy + y, c);
    }
}

int gfx_textn(gfx_t *g, int x, int y, const char *s, int n, uint16_t c) {
    const int rows_ok = y >= 0 && y + 8 <= GFX_H_PX;
    for (int i = 0; i < n && s[i]; i++) {
        unsigned ch = (unsigned char)s[i];
        if (ch < 32 || ch > 126) ch = '?';
        const uint8_t *col = FONT[ch - 32];
        for (int cx = 0; cx < 5; cx++) {
            unsigned bits = col[cx];
            int px = x + cx;
            if (!bits || (unsigned)px >= GFX_W) continue;
            if (rows_ok) { /* a glyph column is 8 consecutive words of memory */
                uint16_t *p = g->px + AT(px, y);
                for (; bits; bits >>= 1, p++)
                    if (bits & 1u) *p = c;
            } else {
                for (int cy = 0; cy < 8; cy++)
                    if (bits & (1u << cy)) gfx_pixel(g, px, y + cy, c);
            }
        }
        x += GFX_FONT_W;
    }
    return x;
}

int gfx_text(gfx_t *g, int x, int y, const char *s, int max_chars, uint16_t c) {
    return gfx_textn(g, x, y, s, max_chars < 0 ? 1 << 20 : max_chars, c);
}

uint16_t gfx_scale(uint16_t c, unsigned level, unsigned max_level) {
    unsigned r = (c >> 11) & 31u, gr = (c >> 5) & 63u, b = c & 31u;
    r = r * level / max_level;
    gr = gr * level / max_level;
    b = b * level / max_level;
    return (uint16_t)((r << 11) | (gr << 5) | b);
}
